/** Total repetitions for an item (sums part counts for #15). */
export function itemCount(item) {
  return item.count ?? item.parts.reduce((s, p) => s + (p.count || 0), 0);
}

/** Pick a part's text for the session: 'morning' | 'evening'. */
export function partText(part, session = 'morning') {
  const ev = session === 'evening';
  return {
    ar: ev && part.arEvening ? part.arEvening : part.ar,
    transliteration: ev && part.transliterationEvening ? part.transliterationEvening : part.transliteration,
    translation: ev && part.translationEvening ? part.translationEvening : part.translation,
  };
}
